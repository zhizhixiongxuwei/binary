func TestOriginalIdentityBoundsCancellationAndNonJarScope(t *testing.T) {
	body := jar(t, map[string][]byte{"META-INF/maven/org.mybatis/mybatis/pom.properties": properties("org.mybatis", "mybatis", "3.5.16")})
	file := filepath.Join(t.TempDir(), "source.jar")
	if err := os.WriteFile(file, body, 0600); err != nil {
		t.Fatal(err)
	}
	hash := sha256.Sum256(body)
	wrong := sha256.Sum256([]byte("different original"))
	if _, err := Detect(context.Background(), file, int64(len(body)), wrong[:]); err == nil {
		t.Fatal("unverified original accepted")
	}
	if _, err := Detect(context.Background(), file, int64(len(body))+1, hash[:]); err == nil {
		t.Fatal("wrong input size accepted")
	}
	if _, err := Detect(context.Background(), file, MaxInputBytes+1, hash[:]); !errors.Is(err, ErrLimit) {
		t.Fatalf("input bound: %v", err)
	}
	ctx, cancel := context.WithCancel(context.Background())
	cancel()
	if _, err := Detect(ctx, file, int64(len(body)), hash[:]); !errors.Is(err, context.Canceled) {
		t.Fatalf("cancelled work continued: %v", err)
	}
	if _, err := detect(t, jar(t, map[string][]byte{"AndroidManifest.xml": []byte("manifest"), "classes.dex": []byte("dex\n")})); err == nil {
		t.Fatal("APK treated as JVM JAR")
	}
	if _, err := detect(t, jar(t, map[string][]byte{"../META-INF/maven/org.mybatis/mybatis/pom.properties": properties("org.mybatis", "mybatis", "3.5.16")})); err == nil {
		t.Fatal("unsafe nested entry accepted")
	}
	if _, err := detect(t, jar(t, map[string][]byte{"META-INF/maven/org.mybatis/mybatis/pom.properties": bytes.Repeat([]byte("x"), int(maxMetadataBytes)+1)})); !errors.Is(err, ErrLimit) {
		t.Fatalf("metadata bound: %v", err)
	}
}

func TestClassHasVerifiedExplicitEmptyMapAndCanonicalDigest(t *testing.T) {
	snapshot, err := detect(t, []byte{0xca, 0xfe, 0xba, 0xbe, 0, 0, 0, 61})
	if err != nil {
		t.Fatal(err)
	}
	if snapshot.Artifacts == nil || snapshot.Digest != "44136fa355b3678a1146ad16f7e8649e94fb4fc21fe77e8310c060f61caaff8a" {
		t.Fatalf("invalid empty fingerprint: %+v", snapshot)
	}
	first := ArtifactsDigest(map[string]string{"org.mybatis:mybatis": "3.5.16", "cn.hutool:hutool-core": "5.8.27"})
	second := ArtifactsDigest(map[string]string{"cn.hutool:hutool-core": "5.8.27", "org.mybatis:mybatis": "3.5.16"})
	canonical := sha256.Sum256([]byte(`{"cn.hutool:hutool-core":"5.8.27","org.mybatis:mybatis":"3.5.16"}`))
	if first != second || first != fmt.Sprintf("%x", canonical) {
		t.Fatal("noncanonical artifacts hash")
	}
	encoded, err := json.Marshal(snapshot)
	if err != nil || !bytes.Contains(encoded, []byte(`"artifacts":{}`)) {
		t.Fatalf("nil map serialized: %s %v", encoded, err)
	}
}

func TestJavaPropertiesEscapesAndManifestSections(t *testing.T) {
	values, err := parseProperties([]byte("groupId: org.myba\\\n tis\nartifactId = mybatis\nversion=3.5.\\u0031\\u0036\n"))
	if err != nil {
		t.Fatal(err)
	}
	if values["groupId"][0] != "org.mybatis" || values["version"][0] != "3.5.16" {
		t.Fatalf("Java properties parsed incorrectly: %+v", values)
	}
	fields := parseManifest([]byte("Implementation-Title: Spring Boot\r\nAutomatic-Module-Name: spring.\r\n boot\r\nImplementation-Version: 3.2.6\r\n\r\nName: fake\r\nImplementation-Version: 99\r\n"))
	if fields["automatic-module-name"][0] != "spring.boot" || len(fields["implementation-version"]) != 1 {
		t.Fatalf("manifest section overrode main identity: %+v", fields)
	}
}

func TestOptionalWMSOriginalFrameworkEvidence(t *testing.T) {
	filename := os.Getenv("BINARYSCAN_FRAMEWORK_JAR")
	if filename == "" {
		t.Skip("set BINARYSCAN_FRAMEWORK_JAR for read-only original JAR verification")
	}
	file, err := os.ReadFile(filename)
	if err != nil {
		t.Fatal(err)
	}
	hash := sha256.Sum256(file)
	snapshot, err := Detect(context.Background(), filename, int64(len(file)), hash[:])
	if err != nil {
		t.Fatal(err)
	}
	for coordinate, version := range map[string]string{"org.springframework.boot:spring-boot": "3.2.6", "org.springframework:spring-beans": "6.1.8", "com.baomidou:mybatis-plus-core": "3.5.6", "org.mybatis:mybatis": "3.5.16", "cn.hutool:hutool-core": "5.8.27", "io.github.linpeilie:mapstruct-plus": "1.3.6", "cn.dev33:sa-token-core": "1.37.0"} {
		if snapshot.Artifacts[coordinate] != version {
			t.Errorf("%s = %q, want %q", coordinate, snapshot.Artifacts[coordinate], version)
		}
	}
	t.Logf("artifacts=%d evidence=%d conflicts=%d diagnostics=%d digest=%s", len(snapshot.Artifacts), len(snapshot.Evidence), len(snapshot.Conflicts), len(snapshot.Diagnostics), snapshot.Digest)
}

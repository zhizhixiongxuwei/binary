func jar(t *testing.T, entries map[string][]byte) []byte {
	t.Helper()
	var buffer bytes.Buffer
	writer := zip.NewWriter(&buffer)
	for name, body := range entries {
		entry, err := writer.Create(name)
		if err != nil {
			t.Fatal(err)
		}
		if _, err = entry.Write(body); err != nil {
			t.Fatal(err)
		}
	}
	if err := writer.Close(); err != nil {
		t.Fatal(err)
	}
	return buffer.Bytes()
}

func properties(group, artifact, version string) []byte {
	return []byte("#Generated by Maven\ngroupId=" + group + "\nartifactId=" + artifact + "\nversion=" + version + "\n")
}
func detect(t *testing.T, body []byte) (Snapshot, error) {
	t.Helper()
	name := filepath.Join(t.TempDir(), "arbitrary-name.bin")
	if err := os.WriteFile(name, body, 0600); err != nil {
		t.Fatal(err)
	}
	digest := sha256.Sum256(body)
	return Detect(context.Background(), name, int64(len(body)), digest[:])
}

func TestDetectUsesExactMavenCoordinatesInOrdinaryAndBootJars(t *testing.T) {
	lib := jar(t, map[string][]byte{"META-INF/maven/cn.hutool/hutool-core/pom.properties": properties("cn.hutool", "hutool-core", "5.8.27")})
	body := jar(t, map[string][]byte{
		"META-INF/maven/org.mybatis/mybatis/pom.properties":   properties("org.mybatis", "mybatis", "3.5.16"),
		"META-INF/maven/org.unrelated/mybatis/pom.properties": properties("org.unrelated", "mybatis", "999.0"),
		"BOOT-INF/lib/unrelated-filename.jar":                 lib,
	})
	snapshot, err := detect(t, body)
	if err != nil {
		t.Fatal(err)
	}
	if len(snapshot.Artifacts) != 2 || snapshot.Artifacts["org.mybatis:mybatis"] != "3.5.16" || snapshot.Artifacts["cn.hutool:hutool-core"] != "5.8.27" {
		t.Fatalf("unexpected artifacts: %+v", snapshot)
	}
	if len(snapshot.Evidence) != 2 || !strings.Contains(snapshot.Evidence[0].EntryPath, "!/META-INF/maven/") || len(snapshot.Evidence[0].JARSHA256) != 64 {
		t.Fatalf("lost provenance: %+v", snapshot.Evidence)
	}
	plain, err := detect(t, lib)
	if err != nil || plain.Artifacts["cn.hutool:hutool-core"] != "5.8.27" {
		t.Fatalf("plain JAR metadata was missed: %+v %v", plain, err)
	}
}

func TestManifestFallbackNeedsExactIdentityVersionAndClass(t *testing.T) {
	manifest := []byte("Manifest-Version: 1.0\r\nImplementation-Title: spring-beans\r\nAutomatic-Module-Name: spring.beans\r\nImplementation-Version: 6.1.8\r\n\r\n")
	className := "org/springframework/beans/factory/BeanFactory.class"
	good := jar(t, map[string][]byte{"META-INF/MANIFEST.MF": manifest, className: {0xca, 0xfe, 0xba, 0xbe, 0, 0, 0, 61}})
	snapshot, err := detect(t, good)
	if err != nil {
		t.Fatal(err)
	}
	if snapshot.Artifacts["org.springframework:spring-beans"] != "6.1.8" || snapshot.Evidence[0].Source != "manifest-and-class" {
		t.Fatalf("manifest proof not recorded: %+v", snapshot)
	}
	for name, entries := range map[string]map[string][]byte{
		"class missing":        {"META-INF/MANIFEST.MF": manifest},
		"invalid class header": {"META-INF/MANIFEST.MF": manifest, className: []byte("notaclass")},
		"wrong module":         {"META-INF/MANIFEST.MF": bytes.ReplaceAll(manifest, []byte("spring.beans"), []byte("vendor.beans")), className: {0xca, 0xfe, 0xba, 0xbe}},
	} {
		t.Run(name, func(t *testing.T) {
			result, err := detect(t, jar(t, entries))
			if err != nil {
				t.Fatal(err)
			}
			if len(result.Artifacts) != 0 {
				t.Fatalf("weak proof accepted: %+v", result)
			}
		})
	}
}

func TestConflictingVersionsAreNotSelected(t *testing.T) {
	one := jar(t, map[string][]byte{"META-INF/maven/org.mybatis/mybatis/pom.properties": properties("org.mybatis", "mybatis", "3.5.16")})
	two := jar(t, map[string][]byte{"META-INF/maven/org.mybatis/mybatis/pom.properties": properties("org.mybatis", "mybatis", "3.5.17")})
	snapshot, err := detect(t, jar(t, map[string][]byte{"BOOT-INF/lib/one.jar": one, "BOOT-INF/lib/two.jar": two}))
	if err != nil {
		t.Fatal(err)
	}
	if len(snapshot.Artifacts) != 0 || len(snapshot.Conflicts) != 1 || len(snapshot.Conflicts[0].Versions) != 2 || len(snapshot.Conflicts[0].Entries) != 2 {
		t.Fatalf("conflict overwritten: %+v", snapshot)
	}
	duplicate := append(properties("org.mybatis", "mybatis", "3.5.16"), []byte("version=3.5.17\n")...)
	snapshot, err = detect(t, jar(t, map[string][]byte{"META-INF/maven/org.mybatis/mybatis/pom.properties": duplicate}))
	if err != nil || len(snapshot.Artifacts) != 0 || len(snapshot.Conflicts) != 1 {
		t.Fatalf("duplicate property overwritten: %+v %v", snapshot, err)
	}
}


CREATE TABLE IF NOT EXISTS llm_explanations (
    id CHAR(36) NOT NULL,
    task_id CHAR(36) NOT NULL,
    source_project_id CHAR(36) NOT NULL,
    source_file_id CHAR(36) NOT NULL,
    created_by BIGINT UNSIGNED NULL,
    source_sha256 BINARY(32) NOT NULL,
    cache_key BINARY(32) NOT NULL,
    scope VARCHAR(16) NOT NULL,
    start_line INT UNSIGNED NOT NULL,
    end_line INT UNSIGNED NOT NULL,
    provider VARCHAR(64) NOT NULL,
    model VARCHAR(200) NOT NULL,
    content MEDIUMTEXT NOT NULL,
    status VARCHAR(16) NOT NULL,
    error_code VARCHAR(64) NOT NULL DEFAULT '',
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    KEY idx_llm_explanations_history (source_file_id, created_at, id),
    KEY idx_llm_explanations_cache (source_file_id, cache_key, status, created_at),
    CONSTRAINT fk_llm_explanations_task FOREIGN KEY (task_id) REFERENCES tasks (id) ON DELETE CASCADE,
    CONSTRAINT fk_llm_explanations_project FOREIGN KEY (source_project_id) REFERENCES source_projects (id) ON DELETE CASCADE,
    CONSTRAINT fk_llm_explanations_file FOREIGN KEY (source_file_id) REFERENCES source_files (id) ON DELETE CASCADE,
    CONSTRAINT fk_llm_explanations_user FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT chk_llm_explanations_scope CHECK (scope IN ('file', 'selection')),
    CONSTRAINT chk_llm_explanations_status CHECK (status IN ('generating', 'completed', 'cancelled', 'failed')),
    CONSTRAINT chk_llm_explanations_range CHECK (start_line > 0 AND end_line >= start_line)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
